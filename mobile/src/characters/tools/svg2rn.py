#!/usr/bin/env python3
"""Convert the layered master art (design/characters/{sisu,aava}.svg) into
react-native-svg modules (mobile/src/characters/art/{sisu,aava}.tsx).

    python3 mobile/src/characters/tools/svg2rn.py

The SVGs are the single source of truth (they are themselves generated by
design/characters/tools/build.py). This script only *transcribes* them: every
path, gradient and clip is kept verbatim; the only changes are
  * attributes -> RN props (stroke-width -> strokeWidth, ...),
  * defs ids get an instance prefix (`${p}clip-face`) so several characters can
    share one web page,
  * the animatable parts are split into separate exports (see PersonaArt in
    art/types.ts): pupils become data (animated circles), brows become numeric
    quadratic curves (morphed), mouth / eyelid variants become components
    (cross-faded), `#arm-right-rest` and `#idea-sparkle` become slots.
"""
from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
PKG = HERE.parent
ROOT = PKG.parents[2]  # repo root
SRC = ROOT / "design" / "characters"
OUT = PKG / "art"
NS = "{http://www.w3.org/2000/svg}"

TAGS = {
    "g": "G",
    "path": "Path",
    "circle": "Circle",
    "ellipse": "Ellipse",
    "rect": "Rect",
    "clipPath": "ClipPath",
    "linearGradient": "LinearGradient",
    "radialGradient": "RadialGradient",
    "stop": "Stop",
    "defs": "Defs",
}
DROP_ATTRS = {"display", "xmlns"}


def camel(name: str) -> str:
    return re.sub(r"-([a-z])", lambda m: m.group(1).upper(), name)


class Conv:
    def __init__(self, persona: str):
        self.persona = persona
        self.prefix = f"{persona}-"
        self.used: set[str] = set()

    def ref(self, value: str) -> str:
        """url(#sisu-clip-face) -> {`url(#${p}clip-face)`}"""
        def rep(m: re.Match) -> str:
            ident = m.group(1)
            if ident.startswith(self.prefix):
                ident = ident[len(self.prefix):]
            return f"url(#${{p}}{ident})"
        return "{`" + re.sub(r"url\(#([^)]+)\)", rep, value) + "`}"

    def attrs(self, el: ET.Element, is_def: bool) -> str:
        out = []
        tag = el.tag.replace(NS, "")
        a = dict(el.attrib)
        if tag == "radialGradient":
            a.setdefault("cx", "0.5")
            a.setdefault("cy", "0.5")
            a.setdefault("r", "0.5")
        for k, v in a.items():
            if k in DROP_ATTRS:
                continue
            if k == "id":
                if is_def:
                    ident = v[len(self.prefix):] if v.startswith(self.prefix) else v
                    out.append(f"id={{`${{p}}{ident}`}}")
                continue
            prop = camel(k)
            if "url(#" in v:
                out.append(f"{prop}={self.ref(v)}")
            else:
                vv = " ".join(v.split())
                out.append(f'{prop}="{vv}"')
        return (" " + " ".join(out)) if out else ""

    def jsx(self, el: ET.Element, ind: int, slots: dict[str, str], in_defs=False) -> str:
        tag = el.tag.replace(NS, "")
        pad = "  " * ind
        eid = el.get("id")
        if eid and eid in slots:
            return f"{pad}{slots[eid]}"
        if tag in ("title", "desc"):
            return ""
        if tag not in TAGS:
            raise ValueError(f"unsupported tag {tag}")
        comp = TAGS[tag]
        self.used.add(comp)
        is_def = in_defs or tag in ("clipPath", "linearGradient", "radialGradient")
        children = [c for c in el if c.tag.replace(NS, "") not in ("title", "desc")]
        # clipPaths that live inside groups must be wrapped in <Defs> for RN.
        if tag == "clipPath" and not in_defs:
            self.used.add("Defs")
            inner = self.jsx(el, ind + 1, slots, in_defs=True)
            return f"{pad}<Defs>\n{inner}\n{pad}</Defs>"
        open_ = f"{pad}<{comp}{self.attrs(el, is_def)}"
        if not children:
            return open_ + " />"
        body = "\n".join(
            s for s in (self.jsx(c, ind + 1, slots, in_defs=is_def or tag == "defs") for c in children) if s
        )
        return f"{open_}>\n{body}\n{pad}</{comp}>"

    def children_jsx(self, el: ET.Element, ind: int, slots: dict[str, str]) -> str:
        return "\n".join(s for s in (self.jsx(c, ind, slots) for c in el) if s)


NUM = r"-?\d+(?:\.\d+)?"


def brow_curve(d: str) -> list[float]:
    m = re.fullmatch(rf"\s*M\s*({NUM})\s+({NUM})\s+Q\s*({NUM})\s+({NUM})\s+({NUM})\s+({NUM})\s*", d)
    if not m:
        raise ValueError(f"brow path is not a single quadratic: {d}")
    return [float(x) for x in m.groups()]


def fmt(v: float) -> str:
    return ("%g" % v)


def build(persona: str) -> str:
    tree = ET.parse(SRC / f"{persona}.svg")
    root = tree.getroot()
    by_id = {el.get("id"): el for el in root.iter() if el.get("id")}
    c = Conv(persona)
    defs = root.find(f"{NS}defs")
    vb = root.get("viewBox")

    def comp(name: str, el: ET.Element, slots: dict[str, str] | None = None,
             extra: list[tuple[str, str]] | None = None, wrap: bool = True) -> str:
        slots = slots or {}
        extra = extra or []
        if wrap:
            el = el  # wrapper keeps its transform; display="none" is dropped (RN uses opacity)
            body = c.jsx(el, 2, slots)
        else:
            inner = "\n".join(s for s in (c.jsx(ch, 3, slots) for ch in el) if s)
            body = f"    <>\n{inner}\n    </>"
        names = ", ".join(["p"] + [n.rstrip("?") for n, _ in extra])
        typ = "Pfx" + ((" & { " + "; ".join(f"{n}: {t}" for n, t in extra) + " }") if extra else "")
        uses_p = "${p}" in body
        guard = "" if uses_p else "  void p;\n"
        return f"const {name} = memo(function {name}({{ {names} }}: {typ}) {{\n{guard}  return (\n{body}\n  );\n}});\n"

    parts: list[str] = []
    parts.append(
        "const TopDefs = memo(function TopDefs({ p }: Pfx) {\n  return (\n"
        + c.jsx(defs, 2, {})
        + "\n  );\n});\n"
    )
    parts.append(comp("HairBack", by_id["hair-back"]))
    parts.append(comp("Body", by_id["body"]))
    parts.append(comp("ArmsRest", by_id["arms-rest"], {"arm-right-rest": "{armRight}"}, [("armRight", "ReactNode")]))
    parts.append(comp("ArmRightRest", by_id["arm-right-rest"]))
    parts.append(comp("Ears", by_id["ears"]))
    parts.append(comp("Head", by_id["head"]))
    parts.append(comp("Eyes", by_id["eyes"], {"pupil-left": "{pupilLeft}", "pupil-right": "{pupilRight}"},
                      [("pupilLeft", "ReactNode"), ("pupilRight", "ReactNode")]))
    parts.append(comp("HairFront", by_id["hair-front"]))
    parts.append(comp("Glasses", by_id["glasses"]))
    sparkle = "idea-sparkle" in by_id
    parts.append(comp("ArmsGesture", by_id["arms-gesture"], {"idea-sparkle": "{sparkle}"} if sparkle else {},
                      [("sparkle?", "ReactNode")]))
    if sparkle:
        parts.append(comp("IdeaSparkle", by_id["idea-sparkle"]))

    # mouth variants: siblings with ids mouth-*; the wrapper transform is applied by the component.
    mouth = by_id["mouth"]
    mouth_variants = {}
    for el in mouth.iter():
        eid = el.get("id") or ""
        if eid.startswith("mouth-"):
            key = camel(eid[len("mouth-"):])
            name = "Mouth" + key[0].upper() + key[1:]
            parts.append(comp(name, el, wrap=False))
            mouth_variants[key] = name

    # eyelids: combine left + right per kind
    lids = by_id["eyelids"]
    lid_variants = {}
    for kind in ("half", "closed", "happy"):
        l, r = by_id[f"eyelid-left-{kind}"], by_id[f"eyelid-right-{kind}"]
        body = "\n".join(s for s in (c.jsx(ch, 3, {}) for ch in list(l) + list(r)) if s)
        name = "Lids" + kind.capitalize()
        guard = "" if "${p}" in body else "  void p;\n"
        parts.append(
            f"const {name} = memo(function {name}({{ p }}: Pfx) {{\n{guard}  return (\n    <>\n{body}\n    </>\n  );\n}});\n"
        )
        lid_variants[kind] = name

    # brows: numeric curves per variant + stroke style
    brows = by_id["brows"]
    brow_data = {}
    stroke = None
    for el in brows.iter():
        eid = el.get("id") or ""
        if eid.startswith("brows-"):
            paths = [ch for ch in el if ch.tag == f"{NS}path"]
            assert len(paths) == 2, eid
            brow_data[eid[len("brows-"):]] = [brow_curve(pth.get("d")) for pth in paths]
            if stroke is None:
                stroke = (paths[0].get("stroke"), paths[0].get("stroke-width"))

    # pupils: circle data
    def pupils(eid: str) -> str:
        rows = []
        for ch in by_id[eid]:
            assert ch.tag == f"{NS}circle", (eid, ch.tag)
            op = ch.get("opacity")
            rows.append(
                f"{{ cx: {ch.get('cx')}, cy: {ch.get('cy')}, r: {ch.get('r')}, fill: '{ch.get('fill')}'"
                + (f", opacity: {op}" if op else "")
                + " }"
            )
        return "[\n    " + ",\n    ".join(rows) + ",\n  ]"

    def tf(eid: str) -> str:
        return by_id[eid].get("transform") or ""

    header = (
        f"/* AUTO-GENERATED by characters/tools/svg2rn.py from design/characters/{persona}.svg.\n"
        f" * Do not edit by hand: change design/characters/tools/build.py, rebuild the SVG, then rerun the script. */\n"
    )
    used = sorted(c.used | {"Defs"})
    imports = (
        "import { memo, type ReactNode } from 'react';\n"
        f"import {{ {', '.join(used)} }} from 'react-native-svg';\n\n"
        "import type { PersonaArt } from './types';\n\n"
        "type Pfx = { p: string };\n\n"
    )
    brow_ts = ",\n    ".join(
        f"{k}: [[{', '.join(fmt(v) for v in a)}], [{', '.join(fmt(v) for v in b)}]]"
        for k, (a, b) in brow_data.items()
    )
    export = f"""
export const {persona.upper()}_ART: PersonaArt = {{
  viewBox: '{vb}',
  TopDefs,
  HairBack,
  Body,
  ArmsRest,
  ArmRightRest,
  Ears,
  Head,
  Eyes,
  HairFront,
  Glasses,
  ArmsGesture,
  IdeaSparkle: {'IdeaSparkle' if sparkle else 'null'},
  headTransform: '{tf('head')}',
  mouthTransform: '{tf('mouth')}',
  bodyTransform: '{tf('body')}',
  mouths: {{ {', '.join(f'{k}: {v}' for k, v in mouth_variants.items())} }},
  lids: {{ {', '.join(f'{k}: {v}' for k, v in lid_variants.items())} }},
  brows: {{
    stroke: '{stroke[0]}',
    strokeWidth: {stroke[1]},
    {brow_ts},
  }},
  pupils: {{
    left: {pupils('pupil-left')},
    right: {pupils('pupil-right')},
  }},
}};
"""
    return header + imports + "\n".join(parts) + export


def main() -> None:
    OUT.mkdir(exist_ok=True)
    for persona in ("sisu", "aava"):
        src = build(persona)
        (OUT / f"{persona}.tsx").write_text(src)
        print(f"wrote {OUT / (persona + '.tsx')} ({len(src)} bytes)")


if __name__ == "__main__":
    sys.exit(main())
